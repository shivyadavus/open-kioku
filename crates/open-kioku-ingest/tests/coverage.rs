use open_kioku_config::OkConfig;
use open_kioku_core::SkipReason;
use open_kioku_ingest::Indexer;
use std::fs;
use std::path::Path;

/// Every discovered source file is either indexed or attributed to exactly one skip
/// reason, per language, so an ingest rule can never drop files without the manifest
/// saying so.
#[test]
fn coverage_attributes_every_source_file_to_indexed_or_a_skip_reason() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(root, "src/Foo.java", "class Foo {}\n");
    write(root, "src/Bar.java", "class Bar {}\n");
    // Source files are exempt from the name-based secret rule and stay indexed.
    write(root, "src/SecretStore.java", "class SecretStore {}\n");
    write(root, "vendor/dep/Dep.java", "class Dep {}\n");
    // Generated source is indexed and flagged, not dropped.
    write(
        root,
        "src/gen/Model.java",
        "// @generated by a tool\nclass Model {}\n",
    );
    write(root, "tool.py", "def run():\n    pass\n");
    // A non-source file the secret rule still drops by name.
    write(root, "config/secrets.json", "{}\n");
    write(root, "README.md", "# readme\n");
    // Not a recognised language: absent from coverage, present in skip_counts.
    write(root, "notes.xyz", "opaque\n");
    // Pruned by name before discovery: never counted, but reported as a blind spot.
    write(root, "build/tool.py", "def build():\n    pass\n");

    let mut config = OkConfig::default();
    config.scip.enabled = false;
    config.history.enabled = false;
    let snapshot = Indexer::default().index_repo(root, &config).unwrap();
    let quality = &snapshot.manifest.quality;
    let coverage = quality
        .coverage
        .as_ref()
        .expect("a full index records coverage");

    let java = &coverage.by_language["java"];
    assert_eq!(java.discovered, 5);
    assert_eq!(java.indexed, 4);
    assert_eq!(java.generated, 1);
    assert_eq!(java.skipped[&SkipReason::Vendor], 1);
    assert_eq!(java.percent(), Some(80.0));

    let json = &coverage.by_language["json"];
    assert_eq!(json.discovered, 1);
    assert_eq!(json.indexed, 0);
    assert_eq!(json.skipped[&SkipReason::SecretPolicy], 1);

    assert_eq!(coverage.by_language["python"].discovered, 1);
    assert_eq!(coverage.by_language["python"].indexed, 1);
    assert_eq!(coverage.pruned_dirs, 1);
    assert_eq!(coverage.walk_errors, 0);
    assert!(coverage
        .summary_line()
        .ends_with("1 directory pruned by name (contents not counted)"));
    // Document-corpus files are in the index and count as indexed.
    assert_eq!(coverage.by_language["markdown"].indexed, 1);
    assert!(!coverage.by_language.contains_key("unknown"));
    assert_eq!(quality.skip_counts[&SkipReason::UnsupportedLanguage], 1);

    for (language, entry) in &coverage.by_language {
        assert_eq!(
            entry.discovered,
            entry.indexed + entry.skipped.values().sum::<usize>(),
            "{language}: every discovered file is indexed or skipped"
        );
    }
    assert_eq!(coverage.discovered, 8);
    assert_eq!(coverage.indexed, 6);
    assert_eq!(coverage.generated, 1);
    assert_eq!(coverage.skipped[&SkipReason::SecretPolicy], 1);
    assert!(coverage.below_warn_threshold());
    assert_eq!(
        coverage.top_skip_reasons(3),
        vec![(SkipReason::Vendor, 1), (SkipReason::SecretPolicy, 1)]
    );
}

fn write(root: &Path, path: &str, content: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}
