/// #684 review: a JavaScript workspace's `packages/` holding a git-ignored first-party
/// `web-gen/` beside one git-ignored restored NuGet package. Only the package is dependencies;
/// the generated TypeScript is first-party source and still caps a TypeScript selection.
#[test]
fn one_restored_package_does_not_price_its_first_party_siblings_as_dependencies() {
    use open_kioku_core::{
        ConfidenceBreakdown, ConfidenceSignalInput, CoverageInput, DependencyEvidence,
        ExcludedDirClass, COVERAGE_SELECTED_LANGUAGE_SIGNAL,
    };

    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(
        root,
        ".gitignore",
        "packages/web-gen/\npackages/Newtonsoft.Json.13.0.1/\n",
    );
    write(root, "packages/ui/package.json", "{\"name\":\"ui\"}\n");
    for index in 0..5 {
        write(
            root,
            &format!("packages/ui/src/view{index}.ts"),
            "export function view() {}\n",
        );
    }
    for index in 0..20 {
        write(
            root,
            &format!("packages/web-gen/client{index}.ts"),
            "export function call() {}\n",
        );
    }
    let package = "packages/Newtonsoft.Json.13.0.1";
    write(
        root,
        &format!("{package}/Newtonsoft.Json.13.0.1.nupkg"),
        "PK",
    );
    write(
        root,
        &format!("{package}/tools/init.ts"),
        "export function init() {}\n",
    );

    let gaps = index_gaps(root);
    let gap = gaps
        .iter()
        .find(|gap| gap.language == "type_script")
        .unwrap_or_else(|| panic!("{gaps:?}"));
    assert_eq!((gap.missing_files, gap.language_files), (21, 26));
    assert_eq!(gap.dependency_files, 1);
    let class_of = |path: &str| {
        gap.excluded_dirs
            .iter()
            .find(|dir| dir.path == path)
            .map(|dir| (dir.class, dir.evidence, dir.files))
    };
    assert_eq!(
        class_of(package),
        Some((
            ExcludedDirClass::Dependencies,
            Some(DependencyEvidence::NugetPackages),
            1
        ))
    );
    assert_eq!(
        class_of("packages"),
        Some((ExcludedDirClass::Unclassified, None, 20))
    );
    assert!(gap.is_source_majority());

    // The first-party files still cap a TypeScript selection.
    let breakdown = ConfidenceBreakdown::from_signals(ConfidenceSignalInput {
        primary_file_count: 2,
        evidence_count: 8,
        exact_reference_count: 2,
        validation_count: 2,
        validation_with_command_count: 2,
        allowed_file_count: 2,
        runtime_signal_count: 1,
        task_relevance: 1.0,
        primary_language_keys: vec!["type_script".into()],
        coverage: CoverageInput::Recorded(vec![gap.clone()]),
        ..Default::default()
    });
    assert!(breakdown.overall_score <= 0.74, "{breakdown:?}");
    assert!(breakdown
        .components
        .iter()
        .any(|component| component.signal == COVERAGE_SELECTED_LANGUAGE_SIGNAL));
}

