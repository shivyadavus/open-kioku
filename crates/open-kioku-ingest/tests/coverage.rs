/// #684 review: a project at the root whose `bin/` holds a committed script. Before a build the
/// project file is no evidence about `bin/`, so the script is indexed. Once the build writes
/// `bin/Debug/` beside it, `bin/` is MSBuild output, and the script is git-tracked source the
/// index does not hold: counted as missing, named in the coverage caveat, and not a forbidden
/// boundary, so an edit to it needs evidence rather than failing as `forbidden_boundary`.
#[test]
fn a_committed_script_in_a_projects_bin_is_never_hidden_as_build_output() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    git(root, &["init", "--quiet"]);
    write(root, ".gitignore", "bin/Debug/\nobj/\n");
    write(
        root,
        "App.csproj",
        "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>\n",
    );
    write(root, "app.py", "def main():\n    pass\n");
    write(root, "bin/release_tool.py", "def release():\n    pass\n");
    git(root, &["add", ".gitignore", "App.csproj", "app.py", "bin"]);

    // No build output yet: `bin/` is walked and the script indexed.
    let snapshot = index(root);
    assert!(snapshot
        .files
        .iter()
        .any(|file| file.path == Path::new("bin/release_tool.py")));
    let coverage = snapshot.manifest.quality.coverage.as_ref().unwrap();
    assert!(coverage.pruned.is_empty(), "{:?}", coverage.pruned);
    assert_eq!(coverage.programming_percent(), Some(100.0));

    // After a build: a git-ignored `bin/Debug/net8.0/App.dll` beside the committed script.
    write(root, "bin/Debug/net8.0/App.dll", "MZ");
    let snapshot = index(root);
    assert!(!snapshot
        .files
        .iter()
        .any(|file| file.path == Path::new("bin/release_tool.py")));
    let coverage = snapshot.manifest.quality.coverage.as_ref().unwrap();
    assert_eq!(
        coverage.pruned,
        vec![PrunedDir {
            path: "bin".into(),
            reason: PruneReason::MsbuildOutput,
            tracked_source_files: Some(1),
        }]
    );
    // Missing source, not hidden output: the ratio drops and the caveat names the directory.
    assert_eq!(coverage.pruned_source_files(), 1);
    let python = &coverage.by_language["python"];
    assert_eq!((python.discovered, python.indexed), (2, 1));
    assert_eq!(python.skipped[&SkipReason::Pruned], 1);
    assert!(coverage.programming_percent() < Some(100.0));
    assert!(
        coverage
            .summary_line()
            .contains("1 git-tracked source file not indexed under MSBuild output directory: bin/"),
        "{}",
        coverage.summary_line()
    );
    assert!(snapshot.skipped_paths.iter().any(|skipped| {
        skipped.path == Path::new("bin/release_tool.py") && skipped.reason == SkipReason::Pruned
    }));
}

